import {registerLexicalTextEntity} from '@lexical/text';
import {
  $applyNodeReplacement,
  addClassNamesToElement,
  defineExtension,
  type EditorConfig,
  type LexicalNode,
  mergeRegister,
  type SerializedTextNode,
  TextNode,
} from 'lexical';

export type SerializedKeywordNode = SerializedTextNode;

export class KeywordNode extends TextNode {
  $config() {
    return this.config('keyword', {extends: TextNode});
  }

  createDOM(config: EditorConfig): HTMLElement {
    const dom = super.createDOM(config);
    dom.style.cursor = 'default';
    // Add to the class names TextNode.createDOM already applied for the text
    // formats rather than replacing them: registerLexicalTextEntity carries
    // the format of the node it replaces over to the KeywordNode, so a
    // keyword typed under an active format has one to render.
    addClassNamesToElement(dom, 'keyword');
    return dom;
  }

  canInsertTextBefore(): boolean {
    return false;
  }

  canInsertTextAfter(): boolean {
    return false;
  }

  isTextEntity(): true {
    return true;
  }
}

export function $createKeywordNode(keyword: string = ''): KeywordNode {
  return $applyNodeReplacement(new KeywordNode(keyword));
}

export function $isKeywordNode(node: LexicalNode | null | undefined): boolean {
  return node instanceof KeywordNode;
}

